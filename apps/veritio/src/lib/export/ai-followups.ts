/**
 * AI follow-up export: one row per follow-up question asked, with the
 * participant's answer. Long format so it joins cleanly to other exports on
 * Participant ID and Parent Question ID.
 */

import type { ExportOptions } from './types'
import { formatCSV, downloadCSV, formatDateForCSV } from './csv/index'
import { formatFollowupAnswer, type AiFollowupEntry } from '../ai-followup/format'

const HEADERS = [
  'Participant ID',
  'Parent Question ID',
  'Parent Question',
  'Follow-up #',
  'Follow-up Question',
  'Follow-up Type',
  'Answer',
  'Response Time (s)',
  'Why It Was Asked',
  'Generated By',
  'Asked At',
]

/** Flatten the grouped GET /ai-followups payload into rows, oldest first. */
export function flattenAiFollowups(grouped: Record<string, AiFollowupEntry[]> | AiFollowupEntry[] | undefined): AiFollowupEntry[] {
  if (!grouped || Array.isArray(grouped)) return []
  return Object.values(grouped)
    .flat()
    .sort((a, b) => a.created_at.localeCompare(b.created_at))
}

export function buildAiFollowupRows(entries: AiFollowupEntry[], filteredParticipantIds?: Set<string> | null): unknown[][] {
  const rows = entries
    .filter((e) => !filteredParticipantIds || filteredParticipantIds.has(e.participant_id))
    .map((e) => [
      e.participant_id,
      e.parent_question_id,
      plainText(e.parent_question_text ?? ''),
      e.position,
      e.question_text,
      e.followup_question_type || 'text',
      formatFollowupAnswer(e),
      e.response?.response_time_ms != null ? (e.response.response_time_ms / 1000).toFixed(1) : '',
      e.trigger_reason ?? '',
      e.model_used === 'template' ? 'Template' : 'AI',
      formatDateForCSV(e.created_at),
    ])
  return [HEADERS, ...rows]
}

export async function exportAiFollowups(entries: AiFollowupEntry[], options: ExportOptions): Promise<void> {
  downloadCSV(options.filename, formatCSV(buildAiFollowupRows(entries, options.filteredParticipantIds)))
}

function plainText(html: string): string {
  return html.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim()
}

